"""How often do the code rules (CC101 to CC105) fire on honest code?

Corpus: every top-level module in the running Python's standard library that has a matching
test file (Lib/foo.py and Lib/test/test_foo.py). Each module is scanned as if an agent had
just added it, with its real test file as the visible tests. This is a noise estimate on
mature, honest code, not on agent patches, and whole files are a harsher input than diffs.

    python experiments/static_fp/run.py
"""

from __future__ import annotations

import sys
import sysconfig
from collections import Counter
from pathlib import Path

from claimcheck.rules import RULES, scan

ROOT = Path(__file__).resolve().parents[2]


def main() -> int:
    lib = Path(sysconfig.get_paths()["stdlib"])
    pairs = sorted((m, lib / "test" / f"test_{m.stem}.py") for m in lib.glob("*.py")
                   if not m.name.startswith("_") and (lib / "test" / f"test_{m.stem}.py").exists())
    fired, per_rule, examples = 0, Counter(), {}
    for module, test in pairs:
        try:
            src, tsrc = module.read_text(encoding="utf-8"), test.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        tests = {"test/" + test.name: tsrc}
        findings = [f for f in scan(tests, dict(tests, **{module.name: src})) if f.rule.startswith("CC1")]
        if findings:
            fired += 1
        for f in findings:
            per_rule[f.rule] += 1
            examples.setdefault(f.rule, []).append(f"{f.path}:{f.line} {f.message}")
    py = sys.version.split()[0]
    lines = [f"# Static code rules on honest code (CPython {py} standard library)", "",
             "Generated by `python experiments/static_fp/run.py`. Each module is scanned as newly added code, "
             "with its own test file as the visible tests.", "",
             f"Modules scanned: {len(pairs)}. Modules with at least one code-rule finding: {fired} "
             f"({fired / len(pairs):.1%}).", "",
             "| rule | severity | findings | modules | example |", "|---|---|---|---|---|"]
    for rid, rule in RULES.items():
        if not rid.startswith("CC1"):
            continue
        ex = examples.get(rid, [])
        mods = len({e.split(":")[0] for e in ex})
        lines.append(f"| {rid} {rule.name} | {rule.severity} | {per_rule[rid]} | {mods} | {ex[0] if ex else ''} |")
    lines += ["", "All findings:", ""] + [f"- {rid}: {e}" for rid in sorted(examples) for e in examples[rid]]
    out = ROOT / "results" / "static-rules-on-stdlib.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:14 + len(RULES)]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
